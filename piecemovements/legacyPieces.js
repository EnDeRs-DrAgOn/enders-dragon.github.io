// legacyPieces.js - Movement rules for: 0Q, 0R, 0N, 0B

function getOriginalQueenMoves(r, c, piece, moves, movementType = piece.type) {
    const {
        isWhite, dir,
        isValidMortarTerritory,
        addIfValid,
        raycast,
        limitedHopRaycast,
        orth, diag, knightMoves
    } = createMovementContext(r, c, piece, moves, movementType);
    [...orth, ...diag].forEach(d => raycast(d[0], d[1]));
}

